// Draws the app icon and writes resources/icon/: icon.svg (the icon: the mark on a transparent
// square), mark.svg (the mark alone, cropped to its bounds) and icon.ico (every Windows size,
// rendered from icon.svg); src/platform/logoMark.ts, the same polygons for the app itself
// (the title bar's logo, icons in other colors); and build/installerSidebar.bmp, the picture
// beside the installer's and uninstaller's first and last pages. Rendering uses a Chromium
// through Playwright, so the outputs are committed and the build does not run this.
import { mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { chromium } from 'playwright-core';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const out = path.join(root, 'resources/icon');

const ORANGE = '#ff7b1c';
const CANVAS = 256;
/** How much of the square the mark's longer side (its width) fills. */
const FILL = 0.96;
const ICO_SIZES = [16, 20, 24, 32, 40, 48, 64, 256];

// The mark is drawn upright on a 48-unit grid, leaned forward 18°, then the whole picture is
// made 10% wider and 10% shorter: "v_" (a terminal prompt ">_" turned a quarter, with its
// cursor) and two speed lines trailing it.
const LEAN = Math.tan((18 * Math.PI) / 180);
const SQUASH = 0.1;
const rect = (x, y, w, h) => [[x, y], [x + w, y], [x + w, y + h], [x, y + h]];
const V = [[3, 7], [9.25, 7], [16, 29.95], [22.75, 7], [29, 7], [19, 41], [13, 41]];
const CURSOR = rect(32, 35, 13, 6);
/** The V's left outer edge; the speed lines end 2.5 units short of it. */
const edge = (y) => 3 + 0.294 * (y - 7);
const speedLine = (y, h, len) => {
  const end = edge(y + h / 2) - 2.5;
  return rect(end - len, y, len, h);
};
const MARK = [speedLine(13, 3.5, 8.5), speedLine(19.5, 3.5, 5.8), V, CURSOR].map((shape) =>
  shape.map(([x, y]) => [(x - LEAN * y) * (1 + SQUASH), y * (1 - SQUASH)]),
);

function bounds(shapes) {
  const xs = shapes.flat().map((p) => p[0]);
  const ys = shapes.flat().map((p) => p[1]);
  const x = Math.min(...xs);
  const y = Math.min(...ys);
  return { x, y, w: Math.max(...xs) - x, h: Math.max(...ys) - y };
}

/** Scales and centres shapes so their longer side is `size`, centred on (cx, cy). */
function fit(shapes, size, cx, cy) {
  const b = bounds(shapes);
  const k = size / Math.max(b.w, b.h);
  return shapes.map((s) => s.map(([x, y]) => [cx + (x - b.x - b.w / 2) * k, cy + (y - b.y - b.h / 2) * k]));
}

const r = (n) => +n.toFixed(2);
const polygons = (shapes) => shapes.map((s) => `  <polygon points="${s.map(([x, y]) => `${r(x)},${r(y)}`).join(' ')}"/>`).join('\n');
const HEADER = '<!-- Generated by scripts/icons.mjs; edit the geometry there. -->';

const placed = fit(MARK, CANVAS * FILL, CANVAS / 2, CANVAS / 2);
const icon = `${HEADER}
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${CANVAS} ${CANVAS}" fill="${ORANGE}">
${polygons(placed)}
</svg>
`;
const b = bounds(MARK);
const mark = `${HEADER}
<svg xmlns="http://www.w3.org/2000/svg" viewBox="${r(b.x)} ${r(b.y)} ${r(b.w)} ${r(b.h)}" fill="${ORANGE}">
${polygons(MARK)}
</svg>
`;

// MARK's last shape is the cursor.
const flat = (shape) => `[${shape.flat().map(r).join(', ')}]`;
const flatList = (shapes) => shapes.map((shape) => `  ${flat(shape)},`).join('\n');
const logoMark = `// Generated by scripts/icons.mjs; edit the geometry there.

/** The logo's own color, the app icon's. */
export const LOGO_COLOR = '${ORANGE}';

/** The mark's bounds (mark.svg's viewBox): x, y, width, height. */
export const LOGO_VIEW_BOX: readonly number[] = [${[b.x, b.y, b.w, b.h].map(r).join(', ')}];

/** The mark but its cursor: the two speed lines and the "v", each polygon as x1, y1, x2, y2, ... */
export const LOGO_STROKES: readonly (readonly number[])[] = [
${flatList(MARK.slice(0, -1))}
];

/** The "_" of "v_", a terminal's cursor: it blinks while Claude works. */
export const LOGO_CURSOR: readonly number[] = ${flat(MARK.at(-1))};

/** The icon's square (icon.svg's viewBox is 0 0 ICON_CANVAS ICON_CANVAS). */
export const ICON_CANVAS = ${CANVAS};

/** The mark's polygons placed on the icon's square, as in icon.svg. */
export const ICON_POLYGONS: readonly (readonly number[])[] = [
${flatList(placed)}
];

/** The sizes icon.ico holds. */
export const ICON_SIZES: readonly number[] = [${ICO_SIZES.join(', ')}];
`;

/** An .ico with one PNG image per size (Windows Vista and later read PNG entries). */
function ico(images) {
  const header = Buffer.alloc(6 + 16 * images.length);
  header.writeUInt16LE(1, 2);
  header.writeUInt16LE(images.length, 4);
  let offset = header.length;
  images.forEach(({ size, data }, i) => {
    const e = 6 + 16 * i;
    header.writeUInt8(size >= 256 ? 0 : size, e);
    header.writeUInt8(size >= 256 ? 0 : size, e + 1);
    header.writeUInt16LE(1, e + 4);
    header.writeUInt16LE(32, e + 6);
    header.writeUInt32LE(data.length, e + 8);
    header.writeUInt32LE(offset, e + 12);
    offset += data.length;
  });
  return Buffer.concat([header, ...images.map((image) => image.data)]);
}

/**
 * NSIS's welcome and finish pages: 164 x 314, the size the pages show it at 100% (they stretch
 * it on scaled displays, which a flat picture survives). The dark editor background of Dark
 * Modern with the mark.
 */
const SIDEBAR = { width: 164, height: 314, background: '#181818', markSize: 96 };

/** A 24-bit BMP, what NSIS takes: rows of BGR from the bottom up, each padded to 4 bytes. */
function bmp(width, height, rgba) {
  const row = Math.ceil((width * 3) / 4) * 4;
  const data = Buffer.alloc(54 + row * height);
  data.write('BM', 0, 'ascii');
  data.writeUInt32LE(data.length, 2);
  data.writeUInt32LE(54, 10);
  data.writeUInt32LE(40, 14);
  data.writeInt32LE(width, 18);
  data.writeInt32LE(height, 22);
  data.writeUInt16LE(1, 26);
  data.writeUInt16LE(24, 28);
  data.writeUInt32LE(row * height, 34);
  for (let y = 0; y < height; y++) {
    const start = 54 + (height - 1 - y) * row;
    for (let x = 0; x < width; x++) {
      const i = (y * width + x) * 4;
      data[start + x * 3] = rgba[i + 2];
      data[start + x * 3 + 1] = rgba[i + 1];
      data[start + x * 3 + 2] = rgba[i];
    }
  }
  return data;
}

/** Playwright's own Chromium if it was downloaded, else Edge (every Windows has it), else Chrome. */
async function launch() {
  for (const channel of [undefined, 'msedge', 'chrome']) {
    try {
      return await chromium.launch(channel ? { channel } : {});
    } catch {
      // try the next one
    }
  }
  throw new Error('no Chromium to render with: install Edge or Chrome, or run `npx playwright install chromium`');
}

mkdirSync(out, { recursive: true });
writeFileSync(path.join(out, 'icon.svg'), icon);
writeFileSync(path.join(out, 'mark.svg'), mark);
writeFileSync(path.join(root, 'src/platform/logoMark.ts'), logoMark);

const browser = await launch();
try {
  const page = await browser.newPage({ deviceScaleFactor: 1 });
  const images = [];
  for (const size of ICO_SIZES) {
    await page.setViewportSize({ width: size, height: size });
    const svg = icon.replace('<svg ', `<svg width="${size}" height="${size}" `);
    await page.setContent(`<style>html, body { margin: 0; background: transparent; } svg { display: block; }</style>${svg}`);
    images.push({ size, data: await page.screenshot({ omitBackground: true, type: 'png' }) });
  }
  writeFileSync(path.join(out, 'icon.ico'), ico(images));

  // Drawn on a canvas, which hands its pixels back (a screenshot would be a PNG to decode).
  const pixels = await page.evaluate(async ({ svg, width, height, background, markSize }) => {
    const canvas = document.createElement('canvas');
    canvas.width = width;
    canvas.height = height;
    const context = canvas.getContext('2d');
    context.fillStyle = background;
    context.fillRect(0, 0, width, height);
    const image = new Image();
    image.src = `data:image/svg+xml;base64,${btoa(svg)}`;
    await image.decode();
    // A little above the middle, where the eye expects it beside the pages' headings.
    context.drawImage(image, (width - markSize) / 2, (height - markSize) / 2 - 24, markSize, markSize);
    return Array.from(context.getImageData(0, 0, width, height).data);
  }, { svg: icon, ...SIDEBAR });
  mkdirSync(path.join(root, 'build'), { recursive: true });
  writeFileSync(path.join(root, 'build/installerSidebar.bmp'), bmp(SIDEBAR.width, SIDEBAR.height, pixels));
  console.log(`resources/icon: icon.svg, mark.svg, icon.ico (${ICO_SIZES.join(', ')}); src/platform/logoMark.ts; build/installerSidebar.bmp`);
} finally {
  await browser.close();
}
